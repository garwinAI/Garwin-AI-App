<?php

declare(strict_types=1);

return static function (PDO $pdo): void {
    $driver = (string) $pdo->getAttribute(PDO::ATTR_DRIVER_NAME);

    if ($driver === 'sqlite') {
        $statements = [
            'CREATE TABLE appzone_items (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                name TEXT NOT NULL,
                description TEXT NOT NULL,
                launch_url TEXT NOT NULL,
                price_cents INTEGER NOT NULL DEFAULT 0,
                is_published INTEGER NOT NULL DEFAULT 0,
                view_count INTEGER NOT NULL DEFAULT 0,
                purchase_count INTEGER NOT NULL DEFAULT 0,
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL
            )',
            'CREATE TABLE appzone_ratings (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                app_id INTEGER NOT NULL REFERENCES appzone_items(id) ON DELETE CASCADE,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL,
                UNIQUE (app_id, user_id)
            )',
            'CREATE TABLE appzone_installs (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                app_id INTEGER NOT NULL REFERENCES appzone_items(id) ON DELETE CASCADE,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                installed_at TEXT NOT NULL,
                UNIQUE (app_id, user_id)
            )',
            'CREATE INDEX appzone_items_published ON appzone_items (is_published, name)',
            'CREATE INDEX appzone_ratings_app ON appzone_ratings (app_id, rating)',
        ];
    } elseif ($driver === 'mysql') {
        $statements = [
            'CREATE TABLE appzone_items (
                id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
                name VARCHAR(120) NOT NULL,
                description TEXT NOT NULL,
                launch_url VARCHAR(2048) NOT NULL,
                price_cents BIGINT UNSIGNED NOT NULL DEFAULT 0,
                is_published TINYINT(1) NOT NULL DEFAULT 0,
                view_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
                purchase_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
                created_at DATETIME NOT NULL,
                updated_at DATETIME NOT NULL,
                INDEX appzone_items_published (is_published, name)
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci',
            'CREATE TABLE appzone_ratings (
                id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
                app_id BIGINT UNSIGNED NOT NULL,
                user_id BIGINT UNSIGNED NOT NULL,
                rating TINYINT UNSIGNED NOT NULL,
                created_at DATETIME NOT NULL,
                updated_at DATETIME NOT NULL,
                UNIQUE KEY appzone_rating_user (app_id, user_id),
                INDEX appzone_ratings_app (app_id, rating),
                CONSTRAINT appzone_ratings_app_fk FOREIGN KEY (app_id) REFERENCES appzone_items(id) ON DELETE CASCADE,
                CONSTRAINT appzone_ratings_user_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci',
            'CREATE TABLE appzone_installs (
                id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
                app_id BIGINT UNSIGNED NOT NULL,
                user_id BIGINT UNSIGNED NOT NULL,
                installed_at DATETIME NOT NULL,
                UNIQUE KEY appzone_install_user (app_id, user_id),
                CONSTRAINT appzone_installs_app_fk FOREIGN KEY (app_id) REFERENCES appzone_items(id) ON DELETE CASCADE,
                CONSTRAINT appzone_installs_user_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci',
        ];
    } elseif ($driver === 'pgsql') {
        $statements = [
            'CREATE TABLE appzone_items (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(120) NOT NULL,
                description TEXT NOT NULL,
                launch_url VARCHAR(2048) NOT NULL,
                price_cents BIGINT NOT NULL DEFAULT 0,
                is_published SMALLINT NOT NULL DEFAULT 0,
                view_count BIGINT NOT NULL DEFAULT 0,
                purchase_count BIGINT NOT NULL DEFAULT 0,
                created_at TIMESTAMP NOT NULL,
                updated_at TIMESTAMP NOT NULL
            )',
            'CREATE INDEX appzone_items_published ON appzone_items (is_published, name)',
            'CREATE TABLE appzone_ratings (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                app_id BIGINT NOT NULL REFERENCES appzone_items(id) ON DELETE CASCADE,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
                created_at TIMESTAMP NOT NULL,
                updated_at TIMESTAMP NOT NULL,
                UNIQUE (app_id, user_id)
            )',
            'CREATE INDEX appzone_ratings_app ON appzone_ratings (app_id, rating)',
            'CREATE TABLE appzone_installs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                app_id BIGINT NOT NULL REFERENCES appzone_items(id) ON DELETE CASCADE,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                installed_at TIMESTAMP NOT NULL,
                UNIQUE (app_id, user_id)
            )',
        ];
    } else {
        throw new RuntimeException('Unsupported migration database driver.');
    }

    foreach ($statements as $statement) {
        $pdo->exec($statement);
    }
};
