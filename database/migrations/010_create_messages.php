<?php

declare(strict_types=1);

return static function (PDO $pdo): void {
    $driver = (string) $pdo->getAttribute(PDO::ATTR_DRIVER_NAME);

    if ($driver === 'sqlite') {
        $statements = [
            'CREATE TABLE messages (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                sender_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                recipient_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                subject TEXT NOT NULL,
                body TEXT NOT NULL,
                is_priority INTEGER NOT NULL DEFAULT 0,
                read_at TEXT NULL,
                created_at TEXT NOT NULL
            )',
            'CREATE INDEX messages_recipient_created ON messages (recipient_user_id, created_at)',
        ];
    } elseif ($driver === 'mysql') {
        $statements = [
            'CREATE TABLE messages (
                id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
                sender_user_id BIGINT UNSIGNED NOT NULL,
                recipient_user_id BIGINT UNSIGNED NOT NULL,
                subject VARCHAR(200) NOT NULL,
                body TEXT NOT NULL,
                is_priority TINYINT(1) NOT NULL DEFAULT 0,
                read_at DATETIME NULL,
                created_at DATETIME NOT NULL,
                INDEX messages_recipient_created (recipient_user_id, created_at),
                CONSTRAINT messages_sender_fk FOREIGN KEY (sender_user_id) REFERENCES users(id) ON DELETE CASCADE,
                CONSTRAINT messages_recipient_fk FOREIGN KEY (recipient_user_id) REFERENCES users(id) ON DELETE CASCADE
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci',
        ];
    } elseif ($driver === 'pgsql') {
        $statements = [
            'CREATE TABLE messages (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                sender_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                recipient_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                subject VARCHAR(200) NOT NULL,
                body TEXT NOT NULL,
                is_priority SMALLINT NOT NULL DEFAULT 0,
                read_at TIMESTAMP NULL,
                created_at TIMESTAMP NOT NULL
            )',
            'CREATE INDEX messages_recipient_created ON messages (recipient_user_id, created_at)',
        ];
    } else {
        throw new RuntimeException('The configured database driver does not support Messenger storage.');
    }

    foreach ($statements as $statement) {
        $pdo->exec($statement);
    }
};
