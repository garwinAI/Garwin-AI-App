<?php

declare(strict_types=1);

return static function (PDO $pdo): void {
    $driver = (string) $pdo->getAttribute(PDO::ATTR_DRIVER_NAME);

    if ($driver === 'sqlite') {
        $statements = [
            'CREATE TABLE workspace_pages (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                page_type TEXT NOT NULL,
                title TEXT NOT NULL,
                content TEXT NOT NULL,
                position INTEGER NOT NULL DEFAULT 0,
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL
            )',
            'CREATE INDEX workspace_pages_user_position ON workspace_pages (user_id, position)',
        ];
    } elseif ($driver === 'mysql') {
        $statements = [
            'CREATE TABLE workspace_pages (
                id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
                user_id BIGINT UNSIGNED NOT NULL,
                page_type VARCHAR(20) NOT NULL,
                title VARCHAR(120) NOT NULL,
                content LONGTEXT NOT NULL,
                position INT NOT NULL DEFAULT 0,
                created_at DATETIME NOT NULL,
                updated_at DATETIME NOT NULL,
                INDEX workspace_pages_user_position (user_id, position),
                CONSTRAINT workspace_pages_user_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci',
        ];
    } elseif ($driver === 'pgsql') {
        $statements = [
            'CREATE TABLE workspace_pages (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                page_type VARCHAR(20) NOT NULL,
                title VARCHAR(120) NOT NULL,
                content TEXT NOT NULL,
                position INTEGER NOT NULL DEFAULT 0,
                created_at TIMESTAMP NOT NULL,
                updated_at TIMESTAMP NOT NULL
            )',
            'CREATE INDEX workspace_pages_user_position ON workspace_pages (user_id, position)',
        ];
    } else {
        throw new RuntimeException('The configured database driver does not support workspace pages.');
    }

    foreach ($statements as $statement) {
        $pdo->exec($statement);
    }
};
