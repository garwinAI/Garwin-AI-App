<?php

declare(strict_types=1);

return static function (PDO $pdo): void {
    $driver = (string) $pdo->getAttribute(PDO::ATTR_DRIVER_NAME);

    if ($driver === 'sqlite') {
        $statements = [
            'CREATE TABLE ai_conversations (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                title TEXT NOT NULL,
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL
            )',
            'CREATE INDEX ai_conversations_user_updated ON ai_conversations (user_id, updated_at)',
            'CREATE TABLE ai_messages (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                conversation_id INTEGER NOT NULL REFERENCES ai_conversations(id) ON DELETE CASCADE,
                role TEXT NOT NULL CHECK (role IN (\'user\', \'assistant\')),
                content TEXT NOT NULL,
                created_at TEXT NOT NULL
            )',
            'CREATE INDEX ai_messages_conversation ON ai_messages (conversation_id, id)',
        ];
    } elseif ($driver === 'mysql') {
        $statements = [
            'CREATE TABLE ai_conversations (
                id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
                user_id BIGINT UNSIGNED NOT NULL,
                title VARCHAR(80) NOT NULL,
                created_at DATETIME NOT NULL,
                updated_at DATETIME NOT NULL,
                INDEX ai_conversations_user_updated (user_id, updated_at),
                CONSTRAINT ai_conversations_user_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci',
            'CREATE TABLE ai_messages (
                id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
                conversation_id BIGINT UNSIGNED NOT NULL,
                role VARCHAR(12) NOT NULL,
                content MEDIUMTEXT NOT NULL,
                created_at DATETIME NOT NULL,
                INDEX ai_messages_conversation (conversation_id, id),
                CONSTRAINT ai_messages_conversation_fk FOREIGN KEY (conversation_id) REFERENCES ai_conversations(id) ON DELETE CASCADE
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci',
        ];
    } elseif ($driver === 'pgsql') {
        $statements = [
            'CREATE TABLE ai_conversations (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                title VARCHAR(80) NOT NULL,
                created_at TIMESTAMP NOT NULL,
                updated_at TIMESTAMP NOT NULL
            )',
            'CREATE INDEX ai_conversations_user_updated ON ai_conversations (user_id, updated_at)',
            'CREATE TABLE ai_messages (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                conversation_id BIGINT NOT NULL REFERENCES ai_conversations(id) ON DELETE CASCADE,
                role VARCHAR(12) NOT NULL CHECK (role IN (\'user\', \'assistant\')),
                content TEXT NOT NULL,
                created_at TIMESTAMP NOT NULL
            )',
            'CREATE INDEX ai_messages_conversation ON ai_messages (conversation_id, id)',
        ];
    } else {
        throw new RuntimeException('Unsupported migration database driver.');
    }

    foreach ($statements as $statement) {
        $pdo->exec($statement);
    }
};
