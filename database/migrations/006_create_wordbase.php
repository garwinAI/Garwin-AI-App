<?php

declare(strict_types=1);

return static function (PDO $pdo): void {
    $driver = (string) $pdo->getAttribute(PDO::ATTR_DRIVER_NAME);

    if ($driver === 'sqlite') {
        $statements = [
            'CREATE TABLE wordbase_documents (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                title TEXT NOT NULL,
                content TEXT NOT NULL DEFAULT "",
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL
            )',
            'CREATE INDEX wordbase_documents_user_updated ON wordbase_documents (user_id, updated_at)',
        ];
    } elseif ($driver === 'mysql') {
        $statements = [
            'CREATE TABLE wordbase_documents (
                id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
                user_id BIGINT UNSIGNED NOT NULL,
                title VARCHAR(255) NOT NULL,
                content LONGTEXT NOT NULL,
                created_at DATETIME NOT NULL,
                updated_at DATETIME NOT NULL,
                INDEX wordbase_documents_user_updated (user_id, updated_at),
                CONSTRAINT wordbase_documents_user_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci',
        ];
    } elseif ($driver === 'pgsql') {
        $statements = [
            'CREATE TABLE wordbase_documents (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                title VARCHAR(255) NOT NULL,
                content TEXT NOT NULL DEFAULT "",
                created_at TIMESTAMP NOT NULL,
                updated_at TIMESTAMP NOT NULL
            )',
            'CREATE INDEX wordbase_documents_user_updated ON wordbase_documents (user_id, updated_at)',
        ];
    } else {
        throw new RuntimeException('The configured database driver does not support Wordbase storage.');
    }

    foreach ($statements as $statement) {
        $pdo->exec($statement);
    }
};
